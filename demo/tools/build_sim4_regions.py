#!/usr/bin/env python3
"""Write demo/sim4-regions.js from Sim 4's regions.js (gravity-sewer-osp main @ 10e6852).

Region manhole indices and baseline surcharge indices refer to Sim 3's GROWTH_RUNS.chambers order,
saved in demo/notes/sim4_source/chambers_index.json. Run from the repo root.
"""
import json, re
SRC = "demo/notes/sim4_source/"
def load(path, start="{"):
    t = open(path).read()
    return json.loads(t[t.index(start):t.rstrip().rstrip(";").rindex("}") + 1])
reg = load(SRC + "regions.js")
sim4 = load(SRC + "sim4.js")
ch = json.load(open(SRC + "chambers_index.json"))
num = lambda i: int(ch[i][2:])
cases = {"design": "ii0.11_flat_uniform_b1_sfree", "beyond": "ii0.25_flat_uniform_b1_sfree", "severe": "ii0.40_flat_uniform_b1_sfree"}
out = {
    "source": "gravity-sewer-osp main @ 10e6852, simulation4/data/regions.js and sim4.js",
    "triage": sim4["triage"],
    "regions": [{"id": r["id"], "name": r["name"], "dwellings": r["dwellings"], "nominal": r["nominal"],
                 "manholes": [num(i) for i in r["manholes"]]} for r in reg["regions"]],
    "baseline": {k: {"tag": tag, "surcharged": [num(i) for i in reg["base"][tag]["surcharged"]],
                     "spilled": [num(i) for i in reg["base"][tag]["spilled"]]} for k, tag in cases.items()},
}
open("demo/sim4-regions.js", "w").write("// Generated by demo/tools/build_sim4_regions.py. Do not edit by hand.\nwindow.OSP_SIM4_REGIONS = " + json.dumps(out, separators=(",", ":")) + ";\n")
print({r["id"]: len(r["manholes"]) for r in out["regions"]}, {k: len(v["surcharged"]) for k, v in out["baseline"].items()})
