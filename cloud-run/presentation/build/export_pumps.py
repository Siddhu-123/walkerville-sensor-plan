#!/usr/bin/env python3
"""Builds data/pumps.json (and .js, and the demo's copy demo/pump-data.js): the pump stations and
their rising mains, drawn on the story map.

    python build/export_pumps.py      # after export_story.py; standard library only

Reads the pinned pump station structures and rising mains (data/source/geometry, see SOURCE.md) and
data/story.json, so every point shares the story's origin and every station is tied to the story's
own nodes. A rising main is recorded as short pieces laid end to end; the pieces are chained from
the station to their last end, as the sandbox does (simulation_src/sim25.py pump_links).

A station is modelled when its rising main discharges into the network that drains to the main
network end (the dead end with the most of the network above it), as the sandbox's domain is.
"""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GEOM = os.path.join(ROOT, "data", "source", "geometry")
DEMO = os.path.join(os.path.dirname(os.path.dirname(ROOT)), "demo", "pump-data.js")
SNAP_M = 12.0       # rising main end to network node; the sandbox's RM_SNAP_M (measured: <= 11.4 m)
JOIN_M = 0.2        # one piece's end to the next piece's start


def features(name):
    return json.load(open(os.path.join(GEOM, name), encoding="utf-8"))["features"]


def main():
    story = json.load(open(os.path.join(ROOT, "data", "story.json"), encoding="utf-8"))
    ox, oy = story["origin_epsg28354"]
    nodes = story["nodes"]
    nn = len(nodes["x"])

    def nearest(x, y):
        return min((math.hypot(x - nodes["x"][i], y - nodes["y"][i]), i) for i in range(nn))

    # the main network end: the dead end that the most nodes drain to
    down = {}
    for p in story["pipes"]:
        down.setdefault(p["a"], []).append(p["b"])

    def ends_below(v):
        seen, stack, ends = set(), [v], set()
        while stack:
            u = stack.pop()
            if u in seen:
                continue
            seen.add(u)
            if not down.get(u):
                ends.add(u)
            stack += down.get(u, [])
        return ends
    below = [ends_below(v) for v in range(nn)]
    counts = {}
    for ends in below:
        for e in ends:
            counts[e] = counts.get(e, 0) + 1
    main_end = max(counts, key=counts.get)

    # rising main pieces, upstream end first
    pieces = []
    for f in features("rising_mains.json"):
        a = f["attributes"]
        pts = [q for path in f["geometry"]["paths"] for q in path]
        if a.get("FLOWDIRECT") == 2:
            pts = pts[::-1]
        pieces.append({"id": a["ID"], "pts": pts, "dia": a["NOMINALDIA"], "year": a["CONST_YEAR"]})

    stations = []
    for f in features("rising_structures.json"):
        a = f["attributes"]
        if not str(a.get("LOCATION", "")).startswith("WWPS"):
            continue        # valves and fittings on the rising mains, not stations
        sx, sy = f["geometry"]["x"], f["geometry"]["y"]
        k = min(range(len(pieces)), key=lambda j: math.hypot(pieces[j]["pts"][0][0] - sx, pieces[j]["pts"][0][1] - sy))
        chain, used = [pieces[k]], {k}
        while True:
            ex, ey = chain[-1]["pts"][-1]
            nxt = [j for j in range(len(pieces)) if j not in used
                   and math.hypot(pieces[j]["pts"][0][0] - ex, pieces[j]["pts"][0][1] - ey) < JOIN_M]
            if not nxt:
                break
            used.add(nxt[0])
            chain.append(pieces[nxt[0]])
        line = []
        for piece in chain:
            for x, y in piece["pts"]:
                q = [round(x - ox, 1), round(y - oy, 1)]
                if not line or line[-2:] != q:
                    line += q
        dw, wet = nearest(line[0], line[1])
        dd, to = nearest(line[-2], line[-1])
        if dw > SNAP_M or dd > SNAP_M:
            raise SystemExit(f"{a['LOCATION']}: rising main ends {dw:.1f} m and {dd:.1f} m from the network")
        length = sum(math.hypot(line[i + 2] - line[i], line[i + 3] - line[i + 1]) for i in range(0, len(line) - 2, 2))
        stations.append({
            "name": a["LOCATION"], "id": a["ID"], "rising_mains": [c["id"] for c in chain],
            "dia": min(c["dia"] for c in chain), "len_m": round(length, 1),
            "wet": wet, "to": to, "za": nodes["inv"][wet], "zb": nodes["inv"][to],
            "modelled": main_end in below[to], "p": line,
        })
        print(f"{a['LOCATION']}: wet well node {wet} ({dw:.1f} m), discharges at node {to} ({dd:.1f} m), "
              f"DN{stations[-1]['dia']} x {length:.1f} m, {'modelled' if stations[-1]['modelled'] else 'NOT modelled'}")

    stations.sort(key=lambda s: s["name"])
    out = {"main_end": main_end, "stations": stations}
    text = json.dumps(out, separators=(",", ":"))
    js = "// Generated by build/export_pumps.py. Do not edit by hand.\nwindow.OSP_PUMPS = " + text + ";\n"
    base = os.path.join(ROOT, "data", "pumps")
    open(base + ".json", "w", encoding="utf-8").write(text)
    open(base + ".js", "w", encoding="utf-8").write(js)
    open(DEMO, "w", encoding="utf-8").write(js)
    print(f"main network end: node {main_end}; {sum(s['modelled'] for s in stations)} of {len(stations)} stations modelled; "
          f"wrote data/pumps.json, data/pumps.js and demo/pump-data.js")


if __name__ == "__main__":
    main()
